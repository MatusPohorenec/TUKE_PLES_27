# The wall's QR (the guest form) in the shape of the TUKE emblem, with the invitation's generator (emblem_qr.py).
#   python wall_emblem.py eval  <url>...                masks and gaps per address
#   python wall_emblem.py write <out.json> <url>=<gap>,<mask> ...   paths for the web + black-on-white PNGs to decode
#   python wall_emblem.py ts    <out.ts>   <url>=<gap>,<mask> ...   the web's module (apps/web/src/components/emblemQr.ts)
# Like the other scripts here it runs from a copy of this folder whose emblem_qr.py and make_logo_qr.py have S and
# ROOT pointing to that copy, with a qr_matrix.json from qr_matrix.cjs (any address: only the designs read it).
# 2026-11-16: eval chose gap 1, mask 2 (as on the invitation: 2 blemishes, 1 bad bit in the first format copy), then
#   python wall_emblem.py ts <repo>/apps/web/src/components/emblemQr.ts \
#     https://srdcom.tuke.sk/zapoj-sa/=1,2 https://srdcom.tuke.sk/vestibul/zapoj-sa/=1,2
import json, sys
from pathlib import Path

HERE = Path(__file__).parent
args = sys.argv[1:]
sys.argv = ['x', 'lib']  # emblem_qr runs neither eval nor final
sys.path.insert(0, str(HERE))
import emblem_qr as eq


def reset(url, gap=1, mask=2):
    eq.URL = url
    eq.GAP, eq.MASK = gap, mask
    eq._FINAL = None
    eq._GRID.clear()


if args[0] == 'eval':
    for url in args[1:]:
        print(url, f'({len(url)} bytes)')
        for gap in (1, 2):
            reset(url, gap)
            for mask in range(8):
                shield, cls, rep, _ = eq.design(gap, mask)
                ok = rep['line_bad'] == 0 and rep['halo_bad'] == 0 and rep['miss'] - len(rep['blemish']) <= 0
                print(f'  gap {gap} mask {mask}: free bits {rep["free_bits"]}, constraints {rep["cons"]}, line unsolved {rep["line_bad"]}, '
                      f'halo unsolved {rep["halo_bad"]}, fixed light under a line {rep["line_fixed_light"]} (format copies {rep["format_line"]}), '
                      f'blemishes {len(rep["blemish"])}, misses {rep["miss"]}, penalty {eq.penalty(shield)}{"  OK" if ok else ""}')
elif args[0] == 'ts':
    entries = []
    for spec in args[2:]:
        url, gm = spec.rsplit('=', 1)
        gap, mask = map(int, gm.split(','))
        reset(url, gap, mask)
        grid, gcls, seed = eq.clean_grid()
        shield, cls, n, cx, cy = eq.final_matrix()
        rows = [''.join('1' if shield[R][C] and cls.get((R, C)) != 'line' else '0' for C in range(n)) for R in range(n)]
        entries.append(f"  // version {eq.VERSION}, error correction {eq.ECL}, gap {gap}, mask {mask}, decoration seed {seed}\n"
                       f"  {json.dumps(url)}: {{\n    modules: {json.dumps(eq.md.outline(rows, n))},\n  }},")
    emblem = eq.ml.emblem_svg_path(0, 0, eq.E)
    Path(args[1]).write_text(
        '// Generated by qr/zdroj/wall_emblem.py (the invitation\'s emblem_qr.py for other addresses): do not edit by hand.\n'
        '// The QR codes of the wall in the shape of the TUKE emblem: the emblem\'s lines are a valid part of each code\n'
        '// (its free codewords are solved so that every module under a line is dark), the modules outside the code\'s\n'
        '// square are decoration. Read by jsQR down to 3 px per module, also light on dark as on the wall.\n\n'
        f'/** The emblem in modules ({eq.E} x {eq.E}); `EMBLEM_LINES` is its outline and the T and U (fill-rule evenodd). */\n'
        f'export const EMBLEM_SIZE = {eq.E};\n'
        f'export const EMBLEM_LINES = {json.dumps(emblem)};\n\n'
        '/** Per address: the dark modules of the code and its decoration, as one path in the same module units. */\n'
        'export const EMBLEM_QR: Record<string, { modules: string }> = {\n' + '\n'.join(entries) + '\n};\n',
        encoding='utf-8')
    print('wrote', args[1], len(entries), 'codes')
elif args[0] == 'write':
    out = {}
    for spec in args[2:]:
        url, gm = spec.rsplit('=', 1)
        gap, mask = map(int, gm.split(','))
        reset(url, gap, mask)
        grid, gcls, seed = eq.clean_grid()
        shield, cls, n, cx, cy = eq.final_matrix()
        rows = [''.join('1' if shield[R][C] and cls.get((R, C)) != 'line' else '0' for C in range(n)) for R in range(n)]
        out[url] = {
            'size': eq.E,
            'emblem': eq.ml.emblem_svg_path(0, 0, eq.E),
            'modules': eq.md.outline(rows, n),
            'version': eq.VERSION, 'ecl': eq.ECL, 'gap': gap, 'mask': mask, 'seed': seed,
        }
        name = url.rstrip('/').rsplit('/', 2)
        tag = '-'.join(p for p in name[-2:] if p and 'tuke.sk' not in p)
        eq.flat_png(1140, (0, 0, 0)).save(HERE / f'wall-{tag}.png')          # 20 px per module, black on white
        (HERE / f'wall-{tag}.svg').write_text(eq.svg('#000', '#fff', pad=4), encoding='utf-8')
        print(url, '->', f'wall-{tag}.png', 'seed', seed, 'modules path', len(out[url]['modules']), 'chars, emblem path', len(out[url]['emblem']))
    Path(args[1]).write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding='utf-8')
