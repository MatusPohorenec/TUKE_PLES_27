// npm run db:dev-setup
// Prepares a local SQL Server for development, mirroring the TUKE hosting:
//  - writes .data/mssql-dev-setup.sql: SQL Server logins on, the databases ples_dev (the ball) and
//    ples_vestibul_dev (the student lobby, a database of its own like at TUKE), both with the collation of TUKE and
//    compatibility level 160 = SQL Server 2022 like TUKE (also on a newer local server), and the login ples_dev with
//    its own default schema and the roles db_ddladmin, db_datareader, db_datawriter in both (the TUKE login is not
//    db_owner either), with a freshly generated password
//  - writes the connection (MSSQL_*, MSSQL_VESTIBUL_DATABASE) into .env, keeping the other lines; creates .env
//    from .env.example if missing
// The password goes only into these two git-ignored files, never to the terminal.
// Run the .sql file in SSMS (localhost, Windows Authentication), then restart the SQL Server service.
import { randomBytes } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const NAME = 'ples_dev'; // the login, and the database of the ball
const DATABASES = [NAME, 'ples_vestibul_dev']; // the ball (MSSQL_DATABASE), the student lobby (MSSQL_VESTIBUL_DATABASE)
const COLLATION = 'SQL_Latin1_General_CP1_CI_AI'; // the collation of the TUKE database
const password = `Pl3s-${randomBytes(18).toString('base64url')}`; // ASCII, meets the Windows password policy

const createDatabases = DATABASES.map(db => `IF DB_ID(N'${db}') IS NULL CREATE DATABASE ${db} COLLATE ${COLLATION};
-- T-SQL of SQL Server 2022 only, like the TUKE server (matters when the local server is newer)
ALTER DATABASE ${db} SET COMPATIBILITY_LEVEL = 160;`).join('\n');
const grants = DATABASES.map(db => `USE ${db};
IF USER_ID(N'${NAME}') IS NULL CREATE USER ${NAME} FOR LOGIN ${NAME} WITH DEFAULT_SCHEMA = ${NAME};
IF SCHEMA_ID(N'${NAME}') IS NULL EXEC (N'CREATE SCHEMA ${NAME} AUTHORIZATION ${NAME}');
ALTER ROLE db_ddladmin ADD MEMBER ${NAME};
ALTER ROLE db_datareader ADD MEMBER ${NAME};
ALTER ROLE db_datawriter ADD MEMBER ${NAME};
GO`).join('\n');

const script = `-- Local SQL Server for the TUKE ball app (generated by npm run db:dev-setup, do not commit).
-- Run in SSMS connected to localhost with Windows Authentication, then restart the service
-- "SQL Server (MSSQLSERVER)" (SQL Server Configuration Manager -> SQL Server Services).
USE master;
-- allow SQL Server logins next to Windows logins (Mixed Mode); takes effect after the restart
EXEC xp_instance_regwrite N'HKEY_LOCAL_MACHINE', N'Software\\Microsoft\\MSSQLServer\\MSSQLServer', N'LoginMode', REG_DWORD, 2;
${createDatabases}
IF SUSER_ID(N'${NAME}') IS NULL
  CREATE LOGIN ${NAME} WITH PASSWORD = N'${password}', DEFAULT_DATABASE = ${NAME}, CHECK_POLICY = OFF;
ELSE
  ALTER LOGIN ${NAME} WITH PASSWORD = N'${password}';
GO
${grants}
SELECT N'ok: databases ${DATABASES.join(' and ')} with the login ${NAME} are ready, now restart the SQL Server service' AS result;
`;
mkdirSync(`${root}.data`, { recursive: true });
writeFileSync(`${root}.data/mssql-dev-setup.sql`, script);

const envFile = `${root}.env`;
let env = existsSync(envFile) ? readFileSync(envFile, 'utf8') : readFileSync(`${root}.env.example`, 'utf8');
const settings = {
  MSSQL_SERVER: 'localhost',
  MSSQL_DATABASE: NAME,
  MSSQL_USER: NAME,
  MSSQL_PASSWORD: password,
  MSSQL_ENCRYPT: 'true',
  MSSQL_TRUST_SERVER_CERTIFICATE: 'true', // a local server has a self-signed certificate
  MSSQL_VESTIBUL_DATABASE: DATABASES[1], // the student lobby: same server and login, its own database
};
for (const [key, value] of Object.entries(settings)) {
  const line = `${key}=${value}`;
  const re = new RegExp(`^#?\\s*${key}=.*$`, 'm');
  env = re.test(env) ? env.replace(re, line) : `${env.replace(/\n*$/, '\n')}${line}\n`;
}
writeFileSync(envFile, env);

console.log(`[db:dev-setup] wrote .data/mssql-dev-setup.sql and the MSSQL_* settings in .env (login ${NAME}, new password).
Next:
  1. SSMS: connect to localhost (Windows Authentication), File -> Open -> .data\\mssql-dev-setup.sql, Execute
  2. SQL Server Configuration Manager -> SQL Server Services -> SQL Server (MSSQLSERVER) -> Restart
     (TCP/IP must be enabled: SQL Server Network Configuration -> Protocols for MSSQLSERVER -> TCP/IP -> Enable)
  3. npm run db:migrate && npm run db:seed
  4. the student lobby: npm run db:migrate -- --venue vestibul && npm run db:seed -- --venue vestibul`);
